import { StrictMode } from "react";
import { createRoot } from "react-dom/client";
import { BrowserRouter } from "react-router-dom";
import App from "./App";
import { AuthProvider } from "./auth/AuthContext";
import "./styles.css";

// Start Pendo once, before the app renders. An empty visitor id lets Pendo reuse the
// previous visitor if it has one, and otherwise starts an anonymous visitor.
pendo.initialize({
  visitor: {
    id: "",
  },
});

createRoot(document.getElementById("root")!).render(
  <StrictMode>
    <BrowserRouter>
      <AuthProvider>
        <App />
      </AuthProvider>
    </BrowserRouter>
  </StrictMode>,
);
